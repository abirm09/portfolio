-- ==============================================================================
-- SUPABASE DATABASE SCHEMA: BLOG POSTS
-- ==============================================================================

-- 1. Create Blogs Table
CREATE TABLE IF NOT EXISTS public.blogs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  slug TEXT UNIQUE NOT NULL,
  excerpt TEXT NOT NULL,
  content TEXT NOT NULL,
  cover_image JSONB NOT NULL DEFAULT '{}'::jsonb,
  category TEXT NOT NULL DEFAULT 'System Design',
  tags JSONB NOT NULL DEFAULT '[]'::jsonb,
  reading_time INTEGER NOT NULL DEFAULT 5,
  published BOOLEAN NOT NULL DEFAULT false,
  featured BOOLEAN NOT NULL DEFAULT false,
  views INTEGER NOT NULL DEFAULT 0,
  author JSONB NOT NULL DEFAULT '{"name": "Abir Mahmud", "role": "Fullstack & Systems Engineer", "avatar": "/images/hero/hero-avatar.png"}'::jsonb,
  published_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()),
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- 2. Indexes for Performance
CREATE INDEX IF NOT EXISTS idx_blogs_slug ON public.blogs(slug);
CREATE INDEX IF NOT EXISTS idx_blogs_published ON public.blogs(published);
CREATE INDEX IF NOT EXISTS idx_blogs_featured ON public.blogs(featured);
CREATE INDEX IF NOT EXISTS idx_blogs_category ON public.blogs(category);
CREATE INDEX IF NOT EXISTS idx_blogs_published_at ON public.blogs(published_at DESC);
CREATE INDEX IF NOT EXISTS idx_blogs_created_at ON public.blogs(created_at DESC);

-- 3. Enable Row Level Security (RLS)
ALTER TABLE public.blogs ENABLE ROW LEVEL SECURITY;

-- 4. Define Blog RLS Policies
-- Public can view published blog posts
DROP POLICY IF EXISTS "Public can view published blogs" ON public.blogs;
CREATE POLICY "Public can view published blogs"
  ON public.blogs
  FOR SELECT
  TO public
  USING (published = true);

-- Authenticated admin users can view all blog posts (including drafts)
DROP POLICY IF EXISTS "Authenticated users can view all blogs" ON public.blogs;
CREATE POLICY "Authenticated users can view all blogs"
  ON public.blogs
  FOR SELECT
  TO authenticated
  USING (true);

-- Authenticated users have full CRUD permissions
DROP POLICY IF EXISTS "Authenticated users can insert blogs" ON public.blogs;
CREATE POLICY "Authenticated users can insert blogs"
  ON public.blogs
  FOR INSERT
  TO authenticated
  WITH CHECK (true);

DROP POLICY IF EXISTS "Authenticated users can update blogs" ON public.blogs;
CREATE POLICY "Authenticated users can update blogs"
  ON public.blogs
  FOR UPDATE
  TO authenticated
  USING (true)
  WITH CHECK (true);

DROP POLICY IF EXISTS "Authenticated users can delete blogs" ON public.blogs;
CREATE POLICY "Authenticated users can delete blogs"
  ON public.blogs
  FOR DELETE
  TO authenticated
  USING (true);

-- 5. Safe View Increment RPC (allows anonymous / public clients to increment views atomically)
CREATE OR REPLACE FUNCTION public.increment_blog_views(target_slug TEXT)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  UPDATE public.blogs
  SET views = views + 1
  WHERE slug = target_slug AND published = true;
END;
$$;

-- Grant execute permissions on view increment RPC
GRANT EXECUTE ON FUNCTION public.increment_blog_views(TEXT) TO anon, authenticated, public;
